let lang = "en"; // Identity V1 / F2: English default

function fmt(s, vars) {
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
}
function t(key, vars) {
  const table = STRINGS[lang] || STRINGS.sv;
  let s = table[key];
  if (s == null) s = STRINGS.sv[key];
  if (s == null) return key;
  if (Array.isArray(s)) return s.slice();
  return fmt(s, vars);
}

/* Applicera statiska data-i18n-strängar i DOM (innerHTML — våra egna strängar). */
function applyStatic(root) {
  try {
    const els = (root || document).querySelectorAll("[data-i18n]");
    els.forEach(el => {
      const v = t(el.getAttribute("data-i18n"));
      if (typeof v === "string") el.innerHTML = v;
    });
    // A8: översatta title/aria-label-attribut
    (root || document).querySelectorAll("[data-i18n-title]").forEach(el => el.setAttribute("title", t(el.getAttribute("data-i18n-title"))));
    (root || document).querySelectorAll("[data-i18n-aria]").forEach(el => el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))));
  } catch (e) {}
}

const api = {
  STRINGS,
  get lang() { return lang; },
  t,
  /* Ställ in språk ('sv'/'en'), applicera statiskt + uppdatera <html lang>. */
  setLang(l) {
    lang = (l === "en") ? "en" : "sv";
    try { document.documentElement.setAttribute("lang", lang); } catch (e) {}
    applyStatic(document);
    return lang;
  },
  applyStatic,
  worldName(id) {
    return t("world_" + id) !== ("world_" + id) ? t("world_" + id) : id;
  },
  worldTag(id) {
    return t("worldtag_" + id);
  },
  famName(id) {
    return t("fam_" + id);
  },
  tips() { return t("tips"); }
};

window.I18N = api;
